#!/bin/sh

# Source-level regression guards for the large-file audit fixes. These checks
# intentionally require no compiler, scanner binary, or generated build tree.

set -eu

root=$(CDPATH= cd -- "$(dirname "$0")/.." && pwd)

contains() {
    file=$1
    text=$2
    if ! grep -F -- "$text" "$root/$file" >/dev/null 2>&1; then
        echo "large-file source guard failed: $file does not contain: $text" >&2
        exit 1
    fi
}

not_contains() {
    file=$1
    text=$2
    if grep -F -- "$text" "$root/$file" >/dev/null 2>&1; then
        echo "large-file source guard failed: $file still contains: $text" >&2
        exit 1
    fi
}

ordered_after() {
    file=$1
    before=$2
    after=$3
    before_line=$(grep -n -F -- "$before" "$root/$file" | head -n 1 | cut -d: -f1)
    after_line=$(grep -n -F -- "$after" "$root/$file" | head -n 1 | cut -d: -f1)
    if [ -z "$before_line" ] || [ -z "$after_line" ] || [ "$before_line" -ge "$after_line" ]; then
        echo "large-file source guard failed: $file does not place '$after' after '$before'" >&2
        exit 1
    fi
}

